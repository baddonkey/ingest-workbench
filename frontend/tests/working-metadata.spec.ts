// Genuine local Keycloak and SQLite/PostgreSQL; preservation qualification stays separate.
import {test,expect} from '@playwright/test';
import {randomUUID,createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';

test.use({actionTimeout:20_000});

test('all navigator descendants, shared file references and pane selection remain reachable',async({page})=>{
  test.setTimeout(120_000);
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.getByRole('textbox',{name:'Username or email'}).fill('operator');
  await page.getByRole('textbox',{name:'Password',exact:true}).fill('operator-local-only');
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page.getByRole('button',{name:'Refresh',exact:true})).toBeEnabled();
  await page.getByRole('textbox',{name:'New transfer title'}).fill('Complete navigators '+randomUUID());
  await page.getByRole('button',{name:'Create',exact:true}).click();
  await page.locator('input[type=file]').first().setInputFiles(resolve('..','fixtures','reference-1.3.zip'));
  await page.getByRole('button',{name:'Inspect & add SIP'}).click();
  await expect(page.getByText('Internal checks passed',{exact:true})).toBeVisible();
  const loaded=page.waitForResponse(response=>response.url().endsWith('/preparation')&&response.ok());
  await page.getByRole('button',{name:'Open Ingest Packager',exact:true}).click();
  const doc=await (await loaded).json();
  const nodes=new Map(doc.nodes.map((node:{id:string;kind:string;title:string})=>[node.id,node]));
  type TreeRow={key:string;object_id:string;parent_key:string|null;depth:number};
  const classificationRows=doc.navigation.classification as TreeRow[],dossierRows=doc.navigation.hierarchy as TreeRow[],inventoryRows=doc.navigation.inventory as TreeRow[];
  const editor=page.getByRole('region',{name:'Versioned metadata editor'});
  const classification=editor.locator('.classification-pane'),content=editor.locator('.content-pane');
  await expect(classification.locator('.metadata-object')).toHaveCount(classificationRows.length);
  await expect(content.locator('.metadata-object')).toHaveCount(dossierRows.length);
  const file=dossierRows.find(row=>(nodes.get(row.object_id) as {kind:string}).kind==='datei')!;
  const fileTitle=(nodes.get(file.object_id) as {title:string}).title;
  await content.locator('[data-navigation-key="'+file.key+'"] .metadata-object').click();
  await expect(content.getByRole('button',{name:'Dossiers',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(content.locator('[data-navigation-key="'+file.key+'"] .metadata-object')).toHaveAttribute('aria-current','true');
  const branch=classificationRows.find(row=>classificationRows.some(child=>child.parent_key===row.key))!;
  const descendants=new Set<string>([branch.key]);
  for(const row of classificationRows)if(row.parent_key&&descendants.has(row.parent_key))descendants.add(row.key);
  const toggle=classification.locator('[data-navigation-key="'+branch.key+'"] .disclosure');
  await toggle.click();
  await expect(classification.locator('.metadata-object')).toHaveCount(classificationRows.length-descendants.size+1);
  await expect(content.locator('.metadata-object')).toHaveCount(dossierRows.length);
  await toggle.click();
  await expect(classification.locator('.metadata-object')).toHaveCount(classificationRows.length);
  await content.getByRole('searchbox').fill(fileTitle);
  await expect(content.locator('[data-navigation-key="'+file.key+'"]')).toBeVisible();
  await expect(content.locator('[data-navigation-key="'+file.parent_key+'"]')).toBeVisible();
  await content.getByRole('searchbox').fill('');
  await content.getByRole('button',{name:'Package content',exact:true}).click();
  await expect(content.locator('.metadata-object')).toHaveCount(inventoryRows.length);
  const inventoryFile=inventoryRows.find(row=>row.object_id===file.object_id)!;
  await content.locator('[data-navigation-key="'+inventoryFile.key+'"] .metadata-object').click();
  await expect(content.getByRole('button',{name:'Package content',exact:true})).toHaveAttribute('aria-pressed','true');
  const classificationFile=classificationRows.find(row=>row.object_id===file.object_id)!;
  const contentList=content.locator('.object-list');
  await contentList.evaluate(element=>{element.style.maxHeight='24px';});
  async function expectInContentViewport(key:string){
    const row=content.locator('[data-navigation-key="'+key+'"]');
    await expect(row.locator('.metadata-object')).toHaveAttribute('aria-current','true');
    await expect.poll(()=>row.evaluate(element=>{
      const list=element.closest('.object-list')!,bounds=list.getBoundingClientRect(),selected=element.getBoundingClientRect();
      return selected.top>=bounds.top-1 && selected.bottom<=bounds.top+list.clientHeight+1;
    })).toBe(true);
  }
  await contentList.evaluate(element=>{element.scrollTop=0;});
  await expect(content.locator('[data-navigation-key="'+inventoryFile.key+'"]')).not.toBeInViewport({ratio:1});
  await classification.locator('[data-navigation-key="'+classificationFile.key+'"] .metadata-object').click();
  await expect(content.getByRole('button',{name:'Package content',exact:true})).toHaveAttribute('aria-pressed','true');
  await expectInContentViewport(inventoryFile.key);
  const hierarchyOnly=classificationRows.find(row=>dossierRows.some(dossier=>dossier.object_id===row.object_id)&&!inventoryRows.some(item=>item.object_id===row.object_id))!;
  await classification.locator('[data-navigation-key="'+hierarchyOnly.key+'"] .metadata-object').click();
  await expect(content.getByRole('button',{name:'Dossiers',exact:true})).toHaveAttribute('aria-pressed','true');
  await expectInContentViewport(dossierRows.find(row=>row.object_id===hierarchyOnly.object_id)!.key);
  await content.locator('[data-navigation-key="'+file.parent_key+'"] .disclosure').click();
  await expect(content.locator('[data-navigation-key="'+file.key+'"]')).toHaveCount(0);
  await content.getByRole('searchbox').fill('No matching navigator object');
  await classification.locator('[data-navigation-key="'+classificationFile.key+'"] .metadata-object').click();
  await expect(content.getByRole('button',{name:'Dossiers',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(content.getByRole('searchbox')).toHaveValue('');
  await expectInContentViewport(file.key);
  await contentList.evaluate(element=>{element.scrollTop=0;});
  await expect(content.locator('[data-navigation-key="'+file.key+'"]')).not.toBeInViewport({ratio:1});
  await classification.locator('[data-navigation-key="'+classificationFile.key+'"] .metadata-object').click();
  await expectInContentViewport(file.key);
  await expect(classification.locator('[data-navigation-key="'+classificationFile.key+'"] .metadata-object')).toBeFocused();
  await contentList.evaluate(element=>{element.style.maxHeight='';});
  await expect(classification.locator('.metadata-object')).toHaveCount(classificationRows.length);
  await page.screenshot({path:resolve('..','var','browser','complete-navigators-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:resolve('..','var','browser','complete-navigators-mobile.png'),fullPage:true});
  expect(errors).toEqual([]);
});

test('full working metadata, applied history, undo/redo, checkpoints and METS/PREMIS downloads',async({page})=>{
  const api=process.env['ARCHIVE_BROWSER_API']||'http://localhost:8000';
  if(api!=='http://localhost:8000')await page.route('http://localhost:8000/api/**',route=>route.continue({url:route.request().url().replace('http://localhost:8000',api)}));
  let token='';const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',async response=>{if(response.url().endsWith('/protocol/openid-connect/token')&&response.ok())token=(await response.json()).access_token;});
  async function login(user:string){
    await page.goto('/');await page.getByRole('textbox',{name:'Username or email'}).fill(user);
    await page.getByRole('textbox',{name:'Password',exact:true}).fill(user+'-local-only');
    await page.getByRole('button',{name:'Sign In',exact:true}).click();
    await expect(page.locator('.identity')).toHaveText(user);await expect(page.getByRole('button',{name:'Refresh',exact:true})).toBeEnabled();
  }
  async function get(path:string){const response=await fetch(api+path,{headers:{Authorization:'Bearer '+token}});expect(response.ok).toBeTruthy();return response.json();}
  await login('operator');const title='Versioned metadata '+randomUUID();
  await page.getByRole('textbox',{name:'New transfer title'}).fill(title);await page.getByRole('button',{name:'Create',exact:true}).click();
  await page.locator('input[type=file]').first().setInputFiles(resolve('..','fixtures','reference-1.3.zip'));
  await page.getByRole('button',{name:'Inspect & add SIP'}).click();await expect(page.getByText('Internal checks passed',{exact:true})).toBeVisible();
  const transfer=(await get('/api/transfers')).find((t:{title:string})=>t.title===title);
  const sip=transfer.sips[0],base='/api/transfers/'+transfer.id+'/sips/'+sip.id+'/preparation';
  await page.getByRole('button',{name:'Open Ingest Packager',exact:true}).click();
  const editor=page.getByRole('region',{name:'Versioned metadata editor'});
  const reason=editor.getByRole('textbox',{name:'Editing context / reason',exact:true});
  await expect(editor.getByRole('textbox',{name:'Submitting organisation',exact:true})).toBeVisible();
  await expect(editor.locator('.metadata-object').filter({hasText:'ablieferung.xsd'})).toHaveCount(0);
  await editor.getByRole('button',{name:'File metadata',exact:true}).click();
  await expect(editor.locator('.metadata-object').filter({hasText:'ablieferung.xsd'})).toBeVisible();
  await editor.getByRole('button',{name:'Metadata hierarchy',exact:true}).click();
  const initial=await get(base);const submission=initial.nodes.find((n:{kind:string})=>n.kind==='ablieferung');
  await editor.locator('[data-object-id="'+submission.id+'"]').click();
  await reason.fill('Archive preparation: review submission and provenance descriptions.');
  await editor.getByRole('textbox',{name:'Submitting organisation',exact:true}).fill('Reviewed submitting organisation');
  await page.route('http://localhost:8000'+base+'/commands',async route=>{const response=await route.fetch({url:api+base+'/commands'});expect(response.ok()).toBeTruthy();await route.abort('failed');},{times:1});
  await editor.locator('.reference-toolbar').getByRole('button',{name:'Save',exact:true}).click();
  await expect(editor.getByRole('alert')).toContainText('Failed to fetch');
  const applied=page.waitForResponse(r=>r.url().endsWith(base+'/commands') && r.ok());
  await editor.locator('.reference-toolbar').getByRole('button',{name:'Save',exact:true}).click();
  const result=await (await applied).json();expect(result.replayed).toBeTruthy();const first=result.operation;
  await expect(editor.locator('.reference-toolbar').getByRole('button',{name:'Save',exact:true})).toBeDisabled();
  let doc=await get(base);expect(doc.history).toHaveLength(1);
  const provenance=doc.nodes.find((n:{kind:string})=>n.kind==='provenienz');
  await editor.locator('[data-object-id="'+provenance.id+'"]').click();
  const description=editor.locator('[data-field-tag="systemBeschreibung"]');
  if(!await description.getByRole('textbox').count())await description.getByRole('button',{name:'Add value',exact:true}).click();
  await description.getByRole('textbox',{name:'System description',exact:true}).fill('A complete editable provenance field, retained as an applied change.');
  await editor.locator('.reference-toolbar').getByRole('button',{name:'Save',exact:true}).click();
  await expect(editor.locator('.reference-toolbar').getByRole('button',{name:'Save',exact:true})).toBeDisabled();
  await editor.getByRole('button',{name:'Undo',exact:true}).click();
  await expect(editor.getByRole('button',{name:'Redo',exact:true})).toBeEnabled();
  await editor.getByRole('button',{name:'Redo',exact:true}).click();
  await expect(description.getByRole('textbox',{name:'System description',exact:true})).toHaveValue('A complete editable provenance field, retained as an applied change.');
  await editor.locator('.reference-toolbar').getByRole('button',{name:/^Edit history/}).click();
  await editor.getByRole('textbox',{name:'Checkpoint name',exact:true}).fill('Metadata reviewed checkpoint');
  await editor.getByRole('button',{name:'Save checkpoint',exact:true}).click();
  await expect(editor.getByRole('textbox',{name:'Checkpoint name',exact:true})).toHaveValue('');
  await editor.getByRole('button',{name:/^Edit history/}).first().click();
  await expect(editor.locator('.metadata-operation')).toHaveCount(5);
  await expect(editor.locator('.metadata-operation').last()).toContainText('Reviewed submitting organisation');
  await editor.locator('.metadata-operation').last().getByRole('button').click();await editor.getByRole('dialog',{name:'History event',exact:true}).getByRole('button',{name:'Compare with working version',exact:true}).click();
  await expect(editor.getByRole('region',{name:'Version comparison'}).or(editor.locator('.version-comparison'))).toContainText('System description');
  doc=await get(base);const checkpoint=doc.history.at(-1);
  const download=page.waitForEvent('download');await editor.locator('.metadata-operation').first().getByRole('button').click();await editor.getByRole('dialog',{name:'History event',exact:true}).getByRole('button',{name:'Download METS/PREMIS evidence',exact:true}).click();await page.keyboard.press('Escape');
  const evidence=readFileSync((await (await download).path())!);expect(createHash('sha256').update(evidence).digest('hex')).toBe(checkpoint.evidence_sha256);
  const icon=await page.request.get('/package-turbo/save.svg');expect(icon.ok()).toBeTruthy();
  const iconProvenance=JSON.parse(readFileSync(resolve('..','references','provenance.json'),'utf8')).package_turbo_imports;
  const pinnedIcon=iconProvenance.files.find((file:{path:string;sha256:string})=>file.path==='web/public/save.svg');
  expect(pinnedIcon).toBeDefined();expect(createHash('sha256').update(await icon.body()).digest('hex')).toBe(pinnedIcon.sha256);
  const language=editor.getByRole('combobox',{name:'Language',exact:true});await language.selectOption('de');
  await expect(editor.getByRole('heading',{name:'Metadaten bearbeiten',exact:true})).toBeVisible();
  await editor.getByRole('combobox',{name:'Sprache',exact:true}).selectOption('fr');await expect(editor.getByRole('heading',{name:'Modifier les métadonnées',exact:true})).toBeVisible();
  await editor.getByRole('combobox',{name:'Langue',exact:true}).selectOption('it');await expect(editor.getByRole('heading',{name:'Modifica metadati',exact:true})).toBeVisible();
  await editor.getByRole('combobox',{name:'Lingua',exact:true}).selectOption('en');
  await editor.locator('.metadata-operation').last().getByRole('button').click();await editor.getByRole('dialog',{name:'History event',exact:true}).getByRole('button',{name:'Restore version',exact:true}).click();
  await expect(editor.locator('.metadata-operation')).toHaveCount(6);
  expect((await get(base)).state.metadata_sha256).toBe(first.after_metadata_sha256);
  const after=await get('/api/transfers/'+transfer.id);expect(after.sips[0]).toEqual(sip);expect(after.working_metadata[sip.id].changed).toBeTruthy();
  await page.reload();await page.locator('button.transfer').filter({hasText:title}).click();await page.getByRole('button',{name:'Ingest Packager',exact:true}).click();
  await expect(editor.getByRole('textbox',{name:'Submitting organisation',exact:true})).toHaveValue('Reviewed submitting organisation');
  await editor.getByRole('button',{name:/^Edit history/}).first().click();await expect(editor.locator('.metadata-operation')).toHaveCount(6);
  await page.screenshot({path:resolve('..','var','browser','working-metadata.png'),fullPage:true});
  await page.getByRole('button',{name:'Sign out',exact:true}).click();await expect(page.getByRole('textbox',{name:'Username or email'})).toBeVisible();
  await login('auditor');await page.locator('button.transfer').filter({hasText:title}).click();await page.getByRole('button',{name:'Ingest Packager',exact:true}).click();
  await expect(editor.getByText('Reader access · editing unavailable',{exact:true})).toBeVisible();
  await expect(editor.getByRole('textbox',{name:'Submitting organisation',exact:true})).toBeDisabled();
  await editor.getByRole('button',{name:/^Edit history/}).first().click();await expect(editor.locator('.metadata-operation')).toHaveCount(6);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await expect(editor.getByRole('button',{name:'Restore version',exact:true})).toHaveCount(0);
  expect((await get(base)).history[0].id).toBe(first.id);expect(errors).toEqual([]);
});
